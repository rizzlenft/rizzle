// Get URL for a guest - returns YouTube if available, Spotify if available, or search fallback
export const getGuestVideoUrl = (name: string): string => {
  // First check YouTube links
  const videoId = guestVideoLinks[name];
  if (videoId) {
    const id = Array.isArray(videoId) ? videoId[0] : videoId;
    return `https://youtube.com/watch?v=${id}`;
  }
  // Then check Spotify links
  const spotifyUrl = guestSpotifyLinks[name];
  if (spotifyUrl) {
    return spotifyUrl;
  }
  // Fallback to YouTube search for the show
  return `https://www.youtube.com/results?search_query=${encodeURIComponent(name + " WIP Meetup OR Matthew Rizzle OR TokenSmart")}`;
};

// Get all video IDs for a guest
export const getAllGuestVideoIds = (name: string): string[] => {
  const videoId = guestVideoLinks[name];
  if (!videoId) return [];
  return Array.isArray(videoId) ? videoId : [videoId];
};

// Get episode count for a guest
export const getGuestEpisodeCount = (name: string): number => {
  const videoId = guestVideoLinks[name];
  if (!videoId) return 0;
  return Array.isArray(videoId) ? videoId.length : 1;
};

// Get YouTube thumbnail URL for a video
export const getYouTubeThumbnail = (videoId: string, quality: 'default' | 'mq' | 'hq' | 'sd' | 'maxres' = 'mq'): string => {
  const qualityMap = {
    default: 'default',
    mq: 'mqdefault',
    hq: 'hqdefault',
    sd: 'sddefault',
    maxres: 'maxresdefault'
  };
  return `https://img.youtube.com/vi/${videoId}/${qualityMap[quality]}.jpg`;
};

// Check if guest is Spotify-only (has Spotify link but no YouTube)
export const isSpotifyOnlyGuest = (name: string): boolean => {
  return !guestVideoLinks[name] && !!guestSpotifyLinks[name];
};

// Get a random episode (returns guest name and video URL)
export const getRandomEpisode = (): { guest: string; videoId: string; url: string } => {
  // Get all guests with direct links
  const guestsWithLinks = Object.keys(guestVideoLinks);
  const randomGuest = guestsWithLinks[Math.floor(Math.random() * guestsWithLinks.length)];
  const videoIds = getAllGuestVideoIds(randomGuest);
  const randomVideoId = videoIds[Math.floor(Math.random() * videoIds.length)];
  
  return {
    guest: randomGuest,
    videoId: randomVideoId,
    url: `https://youtube.com/watch?v=${randomVideoId}`
  };
};

